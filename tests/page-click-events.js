'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..'),read=f=>fs.readFileSync(path.join(root,f),'utf8');
const manifest=JSON.parse(read('manifest.json'));
assert.ok(!manifest.content_scripts.some(x=>x.js.includes('page-click-guard.js')),'ordinary DOM click interceptor must no longer be registered');
assert.ok(manifest.content_scripts.some(x=>x.js.includes('teams-guard.js')&&x.all_frames),'Teams guard remains registered');
assert.ok(manifest.content_scripts.some(x=>x.js.includes('floating-label.js')));
let listeners=0,messages=0;
const window={addEventListener(){listeners++;}};window.top=window;
const chrome={runtime:{sendMessage(){messages++;throw Error('Extension context invalidated');}}};
vm.runInNewContext(read('page-click-guard.js'),{window,chrome});
assert.equal(listeners,0,'inert compatibility script must not consume native site clicks');
assert.equal(messages,0,'no redundant background navigation');
const rules=JSON.parse(read('rules/failsafe.json'));
assert.ok(rules.some(r=>r.action.type==='block'&&r.condition.resourceTypes.includes('main_frame')),'network failsafe remains');
console.log('PASS: ordinary website events are no longer intercepted by DOM script; Teams and network failsafe retained.');
